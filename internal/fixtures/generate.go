// GeneratorVersion changes whenever the output for a given seed and profile
// changes.
const GeneratorVersion = "0.3.4"

// Profile sets the size of a generated set.
type Profile struct {
	Name  string
	Scale int // entities per Land and per road grow with Scale
	Days  int // daily time partitions covered by observations
}

var profiles = []Profile{
	{Name: "tiny", Scale: 1, Days: 2},
	{Name: "ci", Scale: 12, Days: 3},
	{Name: "benchmark", Scale: 400, Days: 7},
}

// Profiles lists the profile names.
func Profiles() []string {
	out := make([]string, len(profiles))
	for i, p := range profiles {
		out[i] = p.Name
	}
	return out
}

