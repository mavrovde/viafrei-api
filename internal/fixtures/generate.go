// line is a WKT line through the points.
func line(ps ...lonLat) string {
	out := "'SRID=4326;LINESTRING("
	for i, p := range ps {
		if i > 0 {
			out += ", "
		}
		out += coord(p.lon) + " " + coord(p.lat)
	}
	return out + ")'"
}

