// Generate writes the seed rows of profile to out and returns the manifest.
// It fails closed: an unknown profile, an empty table, a family without rows
// or any coverage gap is an error, never an empty success.
func Generate(out io.Writer, profile string, seed uint64, contractVersion string) (*Manifest, error) {
	_, m, err := generate(out, profile, seed, contractVersion)
	return m, err
}

// generate writes the seed rows and returns the generator's state with the
// manifest, so Planted can place its rows on the generated world.
func generate(out io.Writer, profile string, seed uint64, contractVersion string) (*gen, *Manifest, error) {
	i := slices.IndexFunc(profiles, func(p Profile) bool { return p.Name == profile })
	if i < 0 {
		return nil, nil, fmt.Errorf("fixtures: unknown profile %q (known: %s)", profile, strings.Join(Profiles(), ", "))
	}
	r := rand.New(rand.NewPCG(seed, seed^0x9e3779b97f4a7c15)) // #nosec G404 -- reproducible test data, not security
	g := &gen{
		p: profiles[i], r: r, names: &namer{r: r}, w: newSQLWriter(out),
		sources: map[string][]source{}, family: map[string]string{},
		perLand: map[string]int{}, perFam: map[string]int{}, edges: map[string]int{}, pointRef: map[string]string{},
		places: map[string][]place{}, stops: map[string][]string{}, contract: contractVersion,
	}
	g.lands = lands(g.names)
	g.w.write("-- Synthetic fixtures generated by viafrei-api fixturegen " + GeneratorVersion +
		". Fictional data, CC0 1.0. Profile " + profile + ", seed " + fmt.Sprint(seed) + ".\n-- Load it in one transaction, for example psql --single-transaction -f seed.sql.\n")
	g.provenance()
	g.regionsAndPlaces()
	g.roadsAndEvents()
	g.energy()
	g.parking()
	g.transit()
	g.weather()
	g.rules()
	g.hydrogen()
	g.speedCameras()
	g.sharing()
	g.pois()
	g.alerts()
	g.zones()
	g.lorry()
	g.plannedWorks()
	g.w.end()
	sum, err := g.w.close()
	if err != nil {
		return nil, nil, fmt.Errorf("fixtures: write: %w", err)
	}
	m := &Manifest{
		GeneratorVersion: GeneratorVersion, Seed: seed, Profile: profile, ContractVersion: contractVersion,
		ReferenceInstant: ReferenceInstant.Format(time.RFC3339),
		Rows:             g.w.rows, RowsPerLand: g.perLand, RowsPerFamily: g.perFam, EdgeCases: g.edges,
		LicenceClasses: map[string]string{},
		EmptyArea:      [4]float64{emptyArea.w, emptyArea.s, emptyArea.e, emptyArea.n},
		Inputs: []Input{
			{Name: "syllable lists and name endings (internal/fixtures/world.go)", Licence: "CC0-1.0"},
			{Name: "value distributions and text templates (internal/fixtures/generate.go)", Licence: "CC0-1.0"},
		},
		Checksum: sum,
	}
	for _, f := range Families {
		m.LicenceClasses[f.Name] = f.Category
	}
	if gaps := m.Check(); len(gaps) > 0 {
		return g, m, errors.New("fixtures: coverage gaps: " + strings.Join(gaps, "; "))
	}
	return g, m, nil
}

func (g *gen) day(d int) time.Time { return ReferenceInstant.AddDate(0, 0, d) }

func (g *gen) end() time.Time { return g.day(g.p.Days) }

// within the generated window, at a random second.
func (g *gen) instant() time.Time {
	return ReferenceInstant.Add(time.Duration(g.r.Int64N(int64(g.p.Days)*86400)) * time.Second)
}

func (g *gen) pick(list []string) string { return list[g.r.IntN(len(list))] }

func (g *gen) land(code string) land { return g.lands[int(code[0]-'0')*10+int(code[1]-'0')-1] }

func landOf(p lonLat) string {
	col := int((p.lon - Germany.w) / ((Germany.e - Germany.w) / 4))
	row := int((p.lat - Germany.s) / ((Germany.n - Germany.s) / 4))
	col = max(0, min(3, col))
	row = max(0, min(3, row))
	return twoDigits(row*4 + col + 1)
}

// counted records one data row against its Land and its source's family.
func (g *gen) counted(landCode, sourceRef string) {
	if landCode != "" {
		g.perLand[landCode]++
	}
	if sourceRef != "" {
		g.perFam[g.family[sourceRef]]++
	}
}

// src picks a source of the domain; every n-th row goes to the stale one.
func (g *gen) src(domain string, families ...string) string {
	cands := g.sources[domain]
	if g.r.IntN(13) == 0 {
		for _, s := range cands {
			if s.stale {
				return s.ref
			}
		}
	}
	fam := families[g.r.IntN(len(families))]
	for _, s := range cands {
		if s.family == fam && !s.stale {
			return s.ref
		}
	}
	panic("fixtures: no source " + fam + " for " + domain)
}

