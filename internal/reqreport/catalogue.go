// Package reqreport maps test results to the requirement catalogue of the
// specification (TEST-001, TEST-002, TST-011): which requirement has which
// tests, at which level, with which result, and whether every automated MUST
// row in the milestone's scope has a passing test.
package reqreport

import (
	"bufio"
	"fmt"
	"io"
	"io/fs"
	"os"
	"regexp"
	"sort"
	"strings"
)

// Requirement is one row of the catalogue.
type Requirement struct {
	ID      string
	Keyword string // MUST, SHOULD, MAY, or "-" when the row states none
	Method  string // verification method (Spec: Conformance and Acceptance, section 2)
	Level   string // test level from the traceability matrix
	Page    string // the wiki page that defines the requirement
}

// automatedMethods run on every pull request (Spec: Conformance and
// Acceptance, section 2). Load, Docs, Review, Ops and Threat rows are
// verified elsewhere.
var automatedMethods = map[string]bool{
	"Unit": true, "Handler": true, "Contract": true, "Mapping": true,
	"Parity": true, "Security": true, "Config": true, "Lint": true,
}

// Automated reports whether the row's method runs on every pull request.
func (r Requirement) Automated() bool { return automatedMethods[r.Method] }

var (
	idPattern  = regexp.MustCompile(`^[A-Z]+(-[A-Z]+)*-[0-9]{3}$`)
	rowPattern = regexp.MustCompile(`^\| ([A-Z]+(?:-[A-Z]+)*-[0-9]{3}) \|`)
	sourceLine = regexp.MustCompile(`^Source: \[\[[^|\]]*\|([^\]]+)\]\]`)
	keywords   = regexp.MustCompile(`\b(MUST|SHOULD|MAY)\b`)
)

const matrixPage = "Spec-Traceability-Matrix.md"

// FromWiki builds the catalogue from a checkout of the wiki: every row of the
// traceability matrix gives the ID, method, level and source page, and the
// row on that page gives the keyword.
func FromWiki(dir string) ([]Requirement, error) {
	// Read through an fs.FS rooted at the checkout: a page name taken from
	// the matrix cannot reach outside it.
	wiki := os.DirFS(dir)
	matrix, err := fs.ReadFile(wiki, matrixPage)
	if err != nil {
		return nil, err
	}
	var out []Requirement
	page := ""
	for _, line := range strings.Split(string(matrix), "\n") {
		if m := sourceLine.FindStringSubmatch(line); m != nil {
			page = m[1]
			continue
		}
		if !rowPattern.MatchString(line) {
			continue
		}
		cells := splitRow(line)
		if len(cells) < 4 {
			return nil, fmt.Errorf("%s: a row with %d cells: %s", matrixPage, len(cells), line)
		}
		out = append(out, Requirement{ID: cells[0], Method: cells[2], Level: cells[3], Page: page})
	}
	if len(out) == 0 {
		return nil, fmt.Errorf("%s: no requirement row read", matrixPage)
	}
	pages := map[string]string{}
	for i, r := range out {
		if r.Page == "" {
			return nil, fmt.Errorf("%s: %s has no Source line above it", matrixPage, r.ID)
		}
		if _, ok := pages[r.Page]; !ok {
			b, err := fs.ReadFile(wiki, r.Page+".md")
			if err != nil {
				return nil, err
			}
			pages[r.Page] = string(b)
		}
		out[i].Keyword = keywordOf(pages[r.Page], r.ID)
	}
	return out, nil
}

// keywordOf returns the strongest keyword in the row that defines id.
func keywordOf(page, id string) string {
	best := "-"
	for _, line := range strings.Split(page, "\n") {
		if !strings.HasPrefix(line, "| "+id+" |") {
			continue
		}
		for _, k := range keywords.FindAllString(line, -1) {
			if rank(k) > rank(best) {
				best = k
			}
		}
	}
	return best
}

func rank(k string) int {
	return map[string]int{"MAY": 1, "SHOULD": 2, "MUST": 3}[k]
}

func splitRow(line string) []string {
	parts := strings.Split(strings.Trim(line, "|"), "|")
	for i := range parts {
		parts[i] = strings.TrimSpace(parts[i])
	}
	return parts
}

// WriteCatalogue writes the catalogue as tab-separated values with a header.
func WriteCatalogue(w io.Writer, reqs []Requirement) error {
	sorted := append([]Requirement(nil), reqs...)
	sort.Slice(sorted, func(i, j int) bool { return sorted[i].ID < sorted[j].ID })
	bw := bufio.NewWriter(w)
	fmt.Fprintln(bw, "# Generated by `go run ./cmd/reqreport catalogue -wiki <wiki checkout>`; do not edit by hand.")
	fmt.Fprintln(bw, "id\tkeyword\tmethod\tlevel\tpage")
	for _, r := range sorted {
		fmt.Fprintf(bw, "%s\t%s\t%s\t%s\t%s\n", r.ID, r.Keyword, r.Method, r.Level, r.Page)
	}
	return bw.Flush()
}

// ReadCatalogue reads what WriteCatalogue wrote. An empty catalogue, a
// duplicate ID or a malformed row is an error.
func ReadCatalogue(r io.Reader) (map[string]Requirement, error) {
	out := map[string]Requirement{}
	sc := bufio.NewScanner(r)
	n := 0
	for sc.Scan() {
		n++
		line := sc.Text()
		if line == "" || strings.HasPrefix(line, "#") || strings.HasPrefix(line, "id\t") {
			continue
		}
		f := strings.Split(line, "\t")
		if len(f) != 5 || !idPattern.MatchString(f[0]) {
			return nil, fmt.Errorf("catalogue line %d is not id, keyword, method, level, page: %q", n, line)
		}
		if _, dup := out[f[0]]; dup {
			return nil, fmt.Errorf("catalogue line %d: %s twice", n, f[0])
		}
		out[f[0]] = Requirement{ID: f[0], Keyword: f[1], Method: f[2], Level: f[3], Page: f[4]}
	}
	if err := sc.Err(); err != nil {
		return nil, err
	}
	if len(out) == 0 {
		return nil, fmt.Errorf("the catalogue holds no requirement")
	}
	return out, nil
}

// ReadScope reads a milestone's in-scope list: one ID per line, `#` starts a
// comment. An empty scope is an error, because a gate over nothing passes.
func ReadScope(r io.Reader) ([]string, error) {
	var out []string
	seen := map[string]bool{}
	sc := bufio.NewScanner(r)
	for sc.Scan() {
		line := strings.TrimSpace(strings.SplitN(sc.Text(), "#", 2)[0])
		if line == "" {
			continue
		}
		if !idPattern.MatchString(line) {
			return nil, fmt.Errorf("scope: %q is not a requirement ID", line)
		}
		if !seen[line] {
			seen[line] = true
			out = append(out, line)
		}
	}
	if err := sc.Err(); err != nil {
		return nil, err
	}
	if len(out) == 0 {
		return nil, fmt.Errorf("the scope lists no requirement")
	}
	return out, nil
}
