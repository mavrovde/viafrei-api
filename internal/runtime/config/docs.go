package config

import (
	"fmt"
	"io"
	"reflect"
	"strings"
)

// Bounds renders a field's validate tag as readable bounds.
func Bounds(f Field) string {
	var min, max string
	var parts []string
	for rule := range strings.SplitSeq(f.Validate, ",") {
		name, param, _ := strings.Cut(rule, "=")
		switch name {
		case "", "omitempty", "required", "dive":
		case "min":
			min = param
		case "max":
			max = param
		case "oneof":
			parts = append(parts, "one of "+strings.ReplaceAll(param, " ", ", "))
		case "hostname_port":
			parts = append(parts, "host:port")
		case "url":
			parts = append(parts, "absolute URL")
		case "startswith":
			parts = append(parts, "starts with "+param)
		case "contract_version":
			parts = append(parts, "major.minor")
		case "cidr":
			parts = append(parts, "CIDR list")
		case "timezone":
			parts = append(parts, "IANA time zone")
		default:
			parts = append(parts, rule)
		}
	}
	switch {
	case min != "" && max != "" && f.Type == "string":
		parts = append([]string{fmt.Sprintf("%s to %s characters", min, max)}, parts...)
	case min != "" && max != "":
		parts = append([]string{min + " to " + max}, parts...)
	case max != "" && f.Type == "string":
		parts = append([]string{"at most " + max + " characters"}, parts...)
	case max != "":
		parts = append([]string{"at most " + max}, parts...)
	case min != "":
		parts = append([]string{"at least " + min}, parts...)
	}
	if len(parts) == 0 {
		return "—"
	}
	return strings.Join(parts, "; ")
}

// WriteReference writes the configuration reference, generated from the
// declaration (CFG-005). docs/configuration.md is this output; a test fails
// when the checked-in file drifts from it.
func WriteReference(w io.Writer) error {
	var b strings.Builder
	b.WriteString("# Configuration reference\n\n")
	b.WriteString("<!-- Generated by `viafrei-api config docs` from internal/runtime/config. Do not edit by hand. -->\n\n")
	b.WriteString("Every tunable of the service is one key below. Sources are layered: the built-in default, then an optional YAML file ")
	fmt.Fprintf(&b, "(path in `%s`), then environment variables. ", FileEnv)
	b.WriteString("The service refuses to start on an unknown key, an unknown variable with the prefix, a value out of bounds or a broken cross-field rule, and lists every violation. ")
	fmt.Fprintf(&b, "Secrets are read only from the environment or from a file named by the `_FILE` variant (one of the two, never both), never from the YAML file, and are never printed. Exit status on a configuration error: %d.\n\n", ExitCode)
	b.WriteString("Cross-field rules: `db.pool_min` ≤ `db.pool_max`; `deadline.reserve` < `deadline.request`; `health.ready_timeout` ≤ `deadline.request`; `db.statement_timeout_floor` < `deadline.request` − `deadline.reserve`; `compose.part_deadline` × the number of overview parts ≤ `deadline.request` − `deadline.reserve`; the sum of `tiers.*.reserved`, `tiers.bulk.max_inflight` and `tiers.per_key_inflight` are each ≤ `db.pool_max`; every `tiers.*.queue_max_wait` < `deadline.request`.\n\n")
	b.WriteString("| Key | Environment | Type | Default | Bounds | Description |\n")
	b.WriteString("|---|---|---|---|---|---|\n")
	for _, f := range Fields() {
		def := "`" + f.Default + "`"
		switch {
		case f.Secret:
			def = "secret, no default"
		case f.Default == "":
			def = "empty"
		}
		env := "`" + f.Env + "`"
		if f.Secret {
			env += " or `" + f.Env + "_FILE`"
		}
		fmt.Fprintf(&b, "| `%s` | %s | %s | %s | %s | %s |\n", f.Key, env, f.Type, def, Bounds(f), f.Desc)
	}
	_, err := io.WriteString(w, b.String())
	return err
}

// Show renders the effective configuration as "key = value" lines, in
// declaration order. A secret shows only whether it is set (CFG-007).
func Show(cfg *Config) []string {
	root := reflect.ValueOf(cfg).Elem()
	lines := make([]string, 0, len(Fields()))
	for _, f := range Fields() {
		v := root.FieldByIndex(f.index)
		var s string
		switch {
		case f.Secret:
			s = "<unset>"
			if sec, _ := v.Interface().(Secret); sec.IsSet() {
				s = "<set>"
			}
		case f.Type == "list":
			s = strings.Join(v.Interface().([]string), ",")
		default:
			s = fmt.Sprint(v.Interface())
		}
		lines = append(lines, f.Key+" = "+s)
	}
	return lines
}
